import { contextBridge, ipcRenderer, webUtils } from 'electron'

/**
 * The entire surface the renderer gets. One function, returning the backend's address and this
 * launch's token.
 *
 * Keeping it this small is the point: with `contextIsolation` and `sandbox` on, a bug in the UI, or
 * in anything it renders, cannot reach the filesystem, spawn a process, or read the vault. Anything
 * that genuinely needs the OS (printing the recovery sheet, listing removable drives) gets its own
 * named channel here, reviewed on its own merits, rather than a general-purpose bridge.
 */
contextBridge.exposeInMainWorld('avocado', {
  connection: () =>
    ipcRenderer.invoke('avocado:connection') as Promise<{
      url: string
      token: string
      vaultState: string
    }>,

  /** Native folder picker for the setup wizard. Returns null if the user cancels. */
  chooseFolder: (startIn?: string, title?: string) =>
    ipcRenderer.invoke('avocado:chooseFolder', startIn, title) as Promise<string | null>,
  chooseFile: (title: string, startIn?: string, extensions?: string[]) =>
    ipcRenderer.invoke('avocado:chooseFile', title, startIn, extensions) as Promise<string | null>,
  revealFolder: (folder: string) =>
    ipcRenderer.invoke('avocado:revealFolder', folder) as Promise<string | null>,
  revealFile: (file: string) =>
    ipcRenderer.invoke('avocado:revealFile', file) as Promise<string | null>,
  openDiskEncryptionSettings: (pane: string) =>
    ipcRenderer.invoke('avocado:openDiskEncryptionSettings', pane) as Promise<string | null>,
  /** Google's consent screen only; the main process refuses anything else. */
  openGoogleConsent: (url: string) =>
    ipcRenderer.invoke('avocado:openGoogleConsent', url) as Promise<string | null>,

  /** Removable volumes only, never this computer's own disk. */
  removableDrives: () =>
    ipcRenderer.invoke('avocado:removableDrives') as Promise<
      { path: string; label: string; freeBytes: number }[]
    >,

  saveRecoveryKey: (drivePath: string, contents: string) =>
    ipcRenderer.invoke('avocado:saveRecoveryKey', drivePath, contents) as Promise<string>,

  /** Renders the current page to a PDF the user picks a location for. Null if they cancel. */
  exportRecoverySheet: () =>
    ipcRenderer.invoke('avocado:exportRecoverySheet') as Promise<string | null>,

  /**
   * Hands a path to the operating system's default application. The path is never chosen by the
   * renderer: the backend decrypts the document into the coffre's own working folder and answers
   * with where it put it, and main refuses anything outside that folder.
   */

  /**
   * Where a dropped file actually lives on disk.
   *
   * <p>Needed because the backend is what reads files, and it reads them by path. Until Electron 32
   * a dropped File carried a `path` property and the renderer could simply read it; that was removed,
   * and `webUtils.getPathForFile` in the preload is what replaced it. This project runs Electron 34,
   * so there is no fallback to keep.</p>
   *
   * <p>It answers a question and grants nothing: the renderer learns where a file the user just
   * dropped came from, and still cannot open it. Reading it remains the backend's job, and the
   * backend checks what it is asked to read.</p>
   */
  pathForFile: (file: File) => webUtils.getPathForFile(file),

  /** Saves generated bytes where the user asks. Used by the modèles and the billing annexe. */
  saveAs: (fileName: string, base64: string) =>
    ipcRenderer.invoke('avocado:saveAs', fileName, base64) as Promise<string | null>,
})
